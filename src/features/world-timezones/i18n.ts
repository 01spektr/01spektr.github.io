export function useWorldTimezonesI18n() {
  const { locale, t } = useI18n();
  const tr = useCallback((source: keyof typeof KEYS) => t(KEYS[source]), [t]);
  const cityName = useCallback((city: CityTimezone) => locale === "ru" ? city.cityRu : city.city, [locale]);
  const countryName = useCallback((city: CityTimezone) => locale === "ru" ? city.countryRu : city.country, [locale]);
  return { locale, t, tr, cityName, countryName };
}

export type WorldTimezonesTranslator = ReturnType<typeof useWorldTimezonesI18n>["tr"];
